/* Music from the data, for Pulses (work/music.js).
   Three sounds, chosen with one button group: Wood, Piano and Concerto. Every note stands for something the archive
   shows: a surviving issue, a printing of a story, a busy or a quiet week. Nothing is generated by AI or a server: the
   notes are made in the browser, from recordings made once, and only while the music is on.
   - Wood: wooden bars for the presses (each surviving issue, its pitch the town's latitude), plucked strings for the
     stories' printings, strings on the season's chord, a felt drum at New Year.
   - Piano (Piano v1): a recorded grand piano over soft strings. The left hand rocks through each bar's chord, one or two
     notes a day; the right hand sings the printings, by steps, higher in the passage's busier weeks; the harmony leans
     to tension while the weeks get busier and resolves as they quieten; the cellos join in the busiest weeks.
   - Concerto (Concerto v1): Piano with winds: the flute opens each rise that will reach a peak, and after the peak the
     clarinet answers, singing the line on its way down.
   No melody of Rachmaninoff's is used: the shape follows the Adagio of his Second Piano Concerto, the notes the archive.
   Made from the saved sketches in docs/notes (2026-11-23-music-sketch-v5.html, Piano v1, and
   2026-11-23-music-sketch-concerto-v1.html, Concerto v1): the engine (engine-v5.js) and the Piano and Concerto
   instruments (adagio-concerto-v1.js) are copied unchanged but for the lines marked "music.js"; the player is adapted
   to Pulses. The design, the measurements and the owner's choices are in docs/notes/2026-11-23-music-discovery.md.
   Recordings (in audio/music/, or from the audio site): Salamander Grand Piano by Alexander Holm (CC BY 3.0); flute and
   clarinet from the VSCO 2 Community Edition orchestra (CC0).
   Off means off: no audio context and no notes until Music.setOn(true); turned off, the context is closed. Turned on,
   Wood starts at once (it needs no recordings) and the recordings of Piano and Concerto load in the background.
   Pulses drives it: Music.data(index) once, Music.view({from, to, story, printings}) for what it plays,
   Music.follow({day, speed, playing}) from its frame loop, Music.setSound('wood' | 'piano' | 'concerto'). */
