// A note's weight. Each newspaper's first issue of the week is struck full and its later issues that week at half
// strength, so a daily's six notes are one beat and five echoes; an issue with more of its pages surviving strikes
// fuller. Papers at one pitch on one day sound as one note, its weight the 4/3-power mean of theirs.
const fullness = (p, d) => Math.max(.7, Math.min(1.6, Math.sqrt((A.pages.get(d * 256 + p) || 4) / 4)));
const weightOf = (p, d) => (firstsOf(UNITS[1], d).get(p) === d ? 1 : .5) * fullness(p, d);
